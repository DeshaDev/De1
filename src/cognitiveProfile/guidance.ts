export function nextStepsAr(risk: RiskLevel, pattern: ProfilePattern): string[] {
  const steps: string[] = [];
  if (pattern === 'general') {
    steps.push('أعد الفحص في يوم آخر وفي وقت يكون فيه الطفل مرتاحًا ومنتبهًا.');
    steps.push('اطلب تقييمًا شاملًا لدى أخصائي (نطق ولغة، نمو، وفحص سمع وبصر).');
    return steps;
  }
  if (risk === 'high') {
    steps.push('ابدأ البرنامج التدريبي الموجّه فورًا: ٥ جلسات أسبوعيًا، ٢٠ جلسة في نحو ٤ أسابيع.');
    steps.push('أحِل الطفل إلى أخصائي صعوبات تعلّم أو أخصائي نفسي تربوي لتقييم شامل.');
    steps.push('شارك التقرير مع معلم الصف لتطبيق الاستراتيجيات الصفية المقترحة.');
  } else if (risk === 'moderate') {
    steps.push('طبّق البرنامج التدريبي الموجّه على المهارة الأضعف لمدة ٢٠ جلسة (نحو ٤ أسابيع).');
    steps.push('أعد الفحص بعد انتهاء البرنامج؛ استمرار الضعف يستدعي الإحالة إلى أخصائي.');
  } else if (risk === 'low') {
    steps.push('استمر في تعليم القراءة المعتاد مع متابعة تقدّم الطفل.');
    steps.push('أعد الفحص بعد سنة دراسية أو عند ظهور صعوبة في القراءة.');
  } else {
    steps.push('أكمل الألعاب المتبقية للحصول على صورة كاملة.');
  }
  if (pattern === 'visual' || pattern === 'mixed') {
    steps.push('تأكّد من فحص نظر حديث.');
  }
  return steps;
}


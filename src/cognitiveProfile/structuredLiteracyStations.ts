import type { LiteracyStationId } from './literacyPracticeProgress';
export type { LiteracyStationId } from './literacyPracticeProgress';

/**
 * Supplemental structured-literacy practice stations for Arabic readers aged 4–8.
 *
 * These are instructional practice activities, not a diagnostic instrument and not a
 * substitute for a validated, individualized intervention. Reading/spelling stations are
 * offered only from age six; morphology from age seven. Younger children receive listening-
 * comprehension activities without being asked to decode print.
 *
 * Fluency practice uses modeled and repeated reading with phrasing and punctuation. It does
 * not time, score, record, or automatically judge a child's voice.
 */

export interface LiteracyOption {
  id: string;
  labelAr: string;
  emoji?: string;
}

export interface LiteracyQuestion {
  id: string;
  promptAr: string;
  /** Instructional sequence level; items at higher levels use more complex patterns. */
  level?: 1 | 2 | 3;
  /** Model narration or spoken prompt. Fully vowelled Arabic is preferred. */
  audio: string[];
  options: LiteracyOption[];
  correctId: string;
  /** Free typed response for production practice such as dictation; options stays empty. */
  responseMode?: 'text';
  explanationAr: string;
  explanationAudio: string[];
}

export interface LiteracyStation {
  id: LiteracyStationId;
  titleAr: string;
  subtitleAr: string;
  purposeAr: string;
  ageNoteAr: string;
  /** Explicit teaching statement shown before independent practice. */
  teachAr: string;
  /** A worked example shown before the child practises. */
  modelAr: string;
  /** Fully vowelled narration for speech synthesis; separate from display copy. */
  teachAudioAr: string;
  /** Fully vowelled model narration for speech synthesis; separate from display copy. */
  modelAudioAr: string;
  questions: LiteracyQuestion[];
}

export interface FluencyPassage {
  titleAr: string;
  /** Phrase-cued lines; preserve punctuation and read for accuracy, phrasing and meaning. */
  linesAr: string[];
  modelAudio: string[];
  reflectionAr: string;
}

/** Creates a reviewed item while keeping spoken narration explicitly authored and vowelled. */
function makeQuestion(
  id: string,
  level: 1 | 2 | 3,
  promptAr: string,
  audio: string[],
  options: LiteracyOption[],
  correctId: string,
  explanationAr: string,
  explanationAudio: string[],
  responseMode?: 'text'
): LiteracyQuestion {
  return {
    id, level, promptAr, audio, options, correctId, explanationAr, explanationAudio,
    ...(responseMode ? { responseMode } : {}),
  };
}


export function getHandDrawnStory(id: string): HandDrawnStory | undefined {
  return HAND_DRAWN_STORIES.find((s) => s.id === id);
}

/**
 * Returns every unique spoken Arabic string needed for studio audio generation
 * (warmup words, story page sentences, single page words, sequence sentences, and quiz questions).
 */
export function collectHandDrawnStoryAudioTexts(): string[] {
  const seen = new Set<string>();
  const add = (t: string) => {
    const clean = t.normalize('NFC').trim();
    if (clean) seen.add(clean);
  };

  for (const story of HAND_DRAWN_STORIES) {
    for (const w of story.warmupWords) add(w.word);
    for (const p of story.pages) {
      add(p.text);
      for (const tok of p.text.split(/\s+/)) {
        const clean = stripArabicPunctuation(tok);
        if (clean) add(clean);
      }
    }
    for (const seq of story.sequenceEvents) add(seq.text);
    for (const q of story.questions) add(q.q);
  }

  return [...seen];
}

const PUNCT_RE = /[،؛,.!?؟:«»"()]/g;

export function stripArabicPunctuation(token: string): string {
  return token.replace(PUNCT_RE, '').trim();
}

export function normalizeArabicWordForMatch(raw: string): string {
  return raw
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
    .replace(PUNCT_RE, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .trim();
}

/** Matches child Web Speech Recognition transcript against sentence words generously. */
export function matchSpokenWords(transcripts: string[], sentenceWords: string[]): boolean[] {
  const spoken = new Set<string>();
  const stripAl = (w: string) => (w.length >= 4 && w.startsWith('ال') ? w.slice(2) : w);

  for (const t of transcripts) {
    for (const part of t.split(/\s+/)) {
      const n = normalizeArabicWordForMatch(part);
      if (n) {
        spoken.add(n);
        spoken.add(stripAl(n));
      }
    }
  }

  return sentenceWords.map((w) => {
    const n = normalizeArabicWordForMatch(w);
    if (!n) return true;
    if (spoken.has(n)) return true;
    const bare = stripAl(n);
    if (spoken.has(bare)) return true;
    if (bare.length >= 3) {
      for (const s of spoken) {
        if (s.length >= 3 && (s.startsWith(bare.slice(0, 3)) || bare.startsWith(s.slice(0, 3)))) {
          return true;
        }
      }
    }
    return false;
  });
}

